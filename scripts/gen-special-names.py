#!/usr/bin/env python3
"""Writes SpecialNames.java: every name Transpiler.java handles in a case label."""
import re
from pathlib import Path
root = Path(__file__).resolve().parent.parent / "src/java/processing/mode/scheme"
src = (root / "Transpiler.java").read_text()
names = set()
for labels in re.findall(r'case\s+((?:"[^"\n]*"\s*,\s*)*"[^"\n]*")\s*(?:->|:)', src):
    names.update(re.findall(r'"([^"]*)"', labels))
names.discard("")
body = ",\n        ".join('"' + n.replace("\\", "\\\\") + '"' for n in sorted(names))
(root / "SpecialNames.java").write_text(f'''package processing.mode.scheme;

import java.util.Set;

/** Generated by scripts/gen-special-names.py from Transpiler.java. Do not edit. */
final class SpecialNames {{
    static final Set<String> ALL = Set.of(
        {body});
}}
''')
print(f"{len(names)} names")
